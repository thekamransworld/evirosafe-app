// The shared half of the Firestore rules generator. Pure functions: no file access, so the tests call them
// directly.
//
// firestore.rules has three generated blocks, each between marker comments:
//   COMMON    role helpers, project scope, yearly counters, notifications   (built here, from src/lib/shared)
//   PTW       permits to work                                                (scripts/ptw-rules-lib.mjs)
//   ACTIONS   corrective and preventive actions                              (scripts/actions-rules-lib.mjs)
// A module adds its block by exporting a model (src/lib/<module>/model.ts) and a builder, and registering
// both in scripts/gen-rules.mjs. Nothing about who may do what is written by hand.

import { buildPtwRules, START_MARK as PTW_START, END_MARK as PTW_END } from './ptw-rules-lib.mjs';
import { buildActionsRules } from './actions-rules-lib.mjs';

const q = s => `'${s}'`;
export const L = a => `[${a.map(q).join(', ')}]`;
const lf = s => s.replace(/\r\n/g, '\n');

/** Marker comments around a generated block. PTW keeps the text it already has in firestore.rules. */
export const MARKS = {
  COMMON: {
    start: '    // >>> COMMON: generated by scripts/gen-rules.mjs from src/lib/shared. Do not edit by hand.',
    end: '    // <<< COMMON',
  },
  PTW: { start: PTW_START, end: PTW_END },
  ACTIONS: {
    start: '    // >>> ACTIONS: generated by scripts/gen-rules.mjs from src/lib/actions/model.ts. Do not edit by hand.',
    end: '    // <<< ACTIONS',
  },
};

/** The one-line rule each block replaces the first time, or the block it must precede. */
export const PLACEMENT = {
  COMMON: { before: PTW_START },
  PTW: { legacy: /^[ \t]*match \/ptws\/\{docId\}[ \t]*\{[^\n]*\}[ \t]*$/m },
  ACTIONS: { legacy: /^[ \t]*match \/actions\/\{docId\}[ \t]*\{[^\n]*\}[ \t]*$/m },
};

export function renderMatches(matches) {
  return matches.map(mt => {
    const lines = [];
    if (mt.comment) lines.push(`    // ${mt.comment}`);
    lines.push(`    match ${mt.path} {`);
    for (const a of mt.allows) lines.push(`      allow ${a.ops.join(', ')}: if ${a.expr};`);
    lines.push('    }');
    return lines.join('\n');
  }).join('\n\n');
}

/**
 * @param shared { roles, notifications } the exports of src/lib/shared/roles.ts and notifications.ts
 * @param counters one { kind, prefix, roles } per module that numbers its documents
 */
export function buildCommonRules({ roles, notifications }, counters) {
  const kinds = counters.map(c => c.kind);
  if (new Set(kinds).size !== kinds.length) throw new Error(`Two modules declare the same counter kind: ${kinds.join(', ')}`);

  const counterChain = counters
    .map(c => `counterId == ${q(c.kind + '_')} + d.org_id + '_' + string(d.year)\n        ? role in ${L(c.roles)}`)
    .join('\n        : ') + '\n        : false';

  const n = notifications;
  const functions = `
    // ── Roles. The lists come from src/lib/shared/roles.ts, the same ones the screens use. ──
    function isStaff(me)     { return me.role in ${L(roles.STAFF)}; }
    function isReviewer(me)  { return me.role in ${L(roles.REVIEWERS)}; }
    function isApprover(me)  { return me.role in ${L(roles.APPROVERS)}; }
    function isOverrider(me) { return me.role in ${L(roles.OVERRIDERS)}; }

    // One pointer read; mirrors isAccessible(). Pass the pointer in so it is read once.
    function inScope(me, data) {
      return me.role == 'ADMIN' ||
        (data.org_id == me.org_id &&
          (me.role == 'ORG_ADMIN' || !('project_id' in data) || data.project_id in me.get('project_ids', [])));
    }

    // ── Yearly counters: one per kind, organisation and year; the value only ever goes up by 1. ──
    function counterIdOk(counterId, d, role) {
      return ${counterChain};
    }

    function counterCreateOk(counterId, d) {
      let me = myPointer();
      return inScope(me, d)
        && d.keys().hasOnly(['org_id', 'year', 'value'])
        && d.value == 1
        && d.year is int
        && counterIdOk(counterId, d, me.role);
    }

    function counterBumpOk(counterId, before, after) {
      let me = myPointer();
      return inScope(me, before)
        && after.keys().hasOnly(['org_id', 'year', 'value'])
        && after.org_id == before.org_id
        && after.year == before.year
        && after.value == before.value + 1
        && counterIdOk(counterId, after, me.role);
    }

    // A create is only valid together with a +1 bump of its counter, in the same transaction.
    function counterBumped(kind, orgId, year) {
      let c = /databases/$(database)/documents/counters/$(kind + '_' + orgId + '_' + string(year));
      return getAfter(c).data.value == (exists(c) ? get(c).data.value : 0) + 1;
    }

    // ── Notifications: written by staff of the organisation for one person; read, marked read and
    //    deleted only by that person. ──
    function notificationCreateOk(d) {
      let me = myPointer();
      return isStaff(me)
        && inScope(me, d)
        && d.keys().hasOnly(${L(n.NOTIFICATION_KEYS)})
        && d.keys().hasAll(${L(n.NOTIFICATION_REQUIRED)})
        && d.user_id is string && d.user_id.size() > 0
        && d.message is string && d.message.size() <= ${n.MAX_NOTIFICATION_MESSAGE}
        && d.get('title', '') is string && d.get('title', '').size() <= ${n.MAX_NOTIFICATION_TITLE}
        && d.read == false;
    }

    function notificationUpdateOk(before, after) {
      let me = myPointer();
      return before.user_id == me.docId
        && after.diff(before).affectedKeys().hasOnly(${L(n.NOTIFICATION_RECIPIENT_EDITS)});
    }`;

  const matches = [
    {
      path: '/counters/{counterId}',
      comment: 'A missing counter must be readable (resource == null) so the first document of a year can create it.',
      allows: [
        { ops: ['get'], expr: 'isSignedIn() && (resource == null || inScope(myPointer(), resource.data))' },
        { ops: ['list'], expr: 'false' },
        { ops: ['create'], expr: 'counterCreateOk(counterId, request.resource.data)' },
        { ops: ['update'], expr: 'counterBumpOk(counterId, resource.data, request.resource.data)' },
        { ops: ['delete'], expr: 'false' },
      ],
    },
    {
      path: '/notifications/{docId}',
      comment: 'Only the recipient reads, marks read or deletes a notification; staff of the organisation create them.',
      allows: [
        { ops: ['read'], expr: 'isSignedIn() && resource.data.user_id == myPointer().docId' },
        { ops: ['create'], expr: 'notificationCreateOk(request.resource.data)' },
        { ops: ['update'], expr: 'notificationUpdateOk(resource.data, request.resource.data)' },
        { ops: ['delete'], expr: 'isSignedIn() && resource.data.user_id == myPointer().docId' },
      ],
    },
  ];

  const header = `${MARKS.COMMON.start}
    // Regenerate with: npm run gen:rules      Verify in CI with: npm run check:rules
    //
    // Helpers every module uses: role checks, project scope, yearly counters (PTW-2026-0007, ACT-2026-0012),
    // and the notification rules.
`;
  const text = `${header}${functions}\n\n${renderMatches(matches)}\n${MARKS.COMMON.end}`;
  return { key: 'COMMON', functions, matches, text };
}

/**
 * Everything the generator emits, in file order.
 * @param models { shared: {roles, notifications}, ptw, actions } module exports
 */
export function buildAllRules(models) {
  const counters = [models.ptw.COUNTER, models.actions.COUNTER];
  const common = buildCommonRules(models.shared, counters);
  const ptw = buildPtwRules(models.ptw);
  const actions = buildActionsRules(models.actions);
  const blocks = [
    { ...common },
    { key: 'PTW', functions: ptw.functions, matches: ptw.matches, text: ptw.text },
    { key: 'ACTIONS', functions: actions.functions, matches: actions.matches, text: actions.text },
  ];
  return {
    blocks,
    /** Every function and match of every block: what the rules simulator is built from. */
    functions: blocks.map(b => b.functions).join('\n'),
    matches: blocks.flatMap(b => b.matches),
  };
}

// ── splicing into firestore.rules ─────────────────────────────────────────

export function extractBlock(rulesText, key) {
  const t = lf(rulesText);
  const { start, end } = MARKS[key];
  const a = t.indexOf(start);
  const b = t.indexOf(end);
  if (a < 0 || b < 0 || b < a) return null;
  return t.slice(a, b + end.length);
}

/** Replaces the block; the first time, replaces the old one-line rule or goes before the block that needs it. Keeps line endings. */
export function spliceBlock(rulesText, key, blockText) {
  const crlf = rulesText.includes('\r\n');
  let t = lf(rulesText);
  const { start, end } = MARKS[key];
  const place = PLACEMENT[key] ?? {};
  const a = t.indexOf(start);
  const b = t.indexOf(end);
  if (a >= 0 && b > a) {
    t = t.slice(0, a) + blockText + t.slice(b + end.length);
  } else if (place.legacy && place.legacy.test(t)) {
    t = t.replace(place.legacy, blockText);
  } else if (place.before && t.indexOf(place.before) >= 0) {
    const i = t.indexOf(place.before);
    t = t.slice(0, i) + blockText + '\n\n' + t.slice(i);
  } else {
    throw new Error(`Could not place the ${key} section in firestore.rules (no markers, no old rule to replace, nothing to put it before).`);
  }
  return crlf ? t.replace(/\n/g, '\r\n') : t;
}

/**
 * Splices every block. PTW and ACTIONS replace their old one-line rules; COMMON goes before PTW, so PTW is
 * placed first (on a file that has never been generated, COMMON has nothing to go before otherwise).
 */
const SPLICE_ORDER = ['PTW', 'COMMON', 'ACTIONS'];
export function spliceAll(rulesText, blocks) {
  let t = rulesText;
  const ordered = [...blocks].sort((a, b) => SPLICE_ORDER.indexOf(a.key) - SPLICE_ORDER.indexOf(b.key));
  for (const b of ordered) t = spliceBlock(t, b.key, b.text);
  return t;
}
